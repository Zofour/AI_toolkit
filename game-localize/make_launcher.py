# -*- coding: utf-8 -*-
"""生成一键启动脚本（GBK + CRLF，Windows 控制台安全）。"""
import os

GAME = r"C:\Users\yourname\Desktop\game！\ss\示例游戏"
SVC = r"C:\chatbox_temp\game-localize"

BAT = """@echo off
chcp 936 >nul
title 诺蒂卡之奴隶们 - 汉化启动
setlocal
set "SVC={svc}"
set "GAME={game}"
set "URL=http://127.0.0.1:8791/health"

curl -s -m 2 %URL% | findstr /c:"ok" >nul
if not errorlevel 1 goto launch

echo [1/2] 启动本机离线翻译引擎（Qwen2.5-1.5B，纯本地，不联网）...
start "翻译服务 Qwen2.5-1.5B" /min cmd /c "cd /d %SVC% && python srv.py --port 8791"

set n=0
:wait
timeout /t 2 >nul
curl -s -m 2 %URL% | findstr /c:"ok" >nul
if not errorlevel 1 goto launch
set /a n+=1
if %n% lss 30 goto wait
echo    翻译引擎没起来，游戏仍会用已缓存的译文启动（首次出现的句子会是日文）。
echo.

:launch
echo [2/2] 启动游戏...
start "" /d "%GAME%\\ReiPatcher" "%GAME%\\ReiPatcher\\ReiPatcher.exe" -c ExampleGame.ini
echo.
echo 游戏已启动。窗口内的快捷键：
echo     Alt+0  翻译控制面板     Alt+T  中/日原文切换     Alt+F  换字体
echo 关掉那个「翻译服务」窗口即可彻底退出翻译引擎。
timeout /t 6 >nul
""".format(game=GAME, svc=SVC)

TXT = """诺蒂卡之奴隶们 —— 本机离线汉化（说明）

一、怎么开
  双击游戏目录下的  汉化启动.bat
  它会先启动本机的离线翻译引擎（Qwen2.5-1.5B，纯本地推理、不联网），
  等引擎就绪后再启动游戏。第一次启动要等 5~15 秒（模型加载）。

二、汉化是怎么工作的
  · 游戏自带 XUnity.AutoTranslator，我把它的翻译服务指向了本机
    127.0.0.1:8791（C:\\chatbox_temp\\game-localize\\srv.py）。
  · 模型只在你本机跑，不依赖 Ollama、不联网。
  · 已经译好的句子存在
      AutoTranslator\\Translation\\zh\\Text\\_AutoGeneratedTranslations.txt
    这是静态译文，启动即中文、零延迟；新出现的句子才会现翻（约 0.5~3 秒/句）。
  · 专用术语（开始游戏/设置/退出/客人/房间…）走固定术语表
      C:\\chatbox_temp\\game-localize\\glossary.json
    可自己往里加词，改完重启翻译服务生效。

三、常用快捷键
  Alt+0  打开机翻控制面板（可重载译文、看状态）
  Alt+T  中文 / 日文原文 来回切换
  Alt+F  切换字体

四、想提升质量
  · 换更强引擎：关掉翻译服务窗口，然后在
      C:\\chatbox_temp\\game-localize
    里运行
      python srv.py --engine ollama --ollama-model gemma3:12b
    再启动游戏即可（需要本机 Ollama 已开）。质量更好，速度慢一些。

五、出问题怎么办
  · 全是日文：确认「翻译服务 Qwen2.5-1.5B」窗口还开着；
    日志在 C:\\chatbox_temp\\game-localize\\server.log
  · 某句一直不翻：多半是带特效标签的富文本，按 Alt+T 切一下可重触发。
  · 恢复原状：把 AutoTranslator\\Config.ini.orig_bak 覆盖回 Config.ini。
"""

def w(path, text, enc="gbk"):
    with open(path, "w", encoding=enc, newline="\r\n") as f:
        f.write(text)
    print("wrote", path)

w(os.path.join(GAME, "汉化启动.bat"), BAT)
w(os.path.join(GAME, "汉化说明.txt"), TXT)
w(os.path.join(SVC, "汉化启动.bat"), BAT)
